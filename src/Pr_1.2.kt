fun main() {
    val num = 50
    val doubleNum = num.toDouble()
    val str1 = "25"
    val intNum = str1.toInt()
    val str2 = "45.5"
    val doubleNum2 = str2.toDouble()
    println("Integer value: $num")
    println("Integer to Double: $doubleNum")
    println("String value: $str1")
    println("String to Integer: $intNum")
    println("String value: $str2")
    println("String to Double: $doubleNum2")
}