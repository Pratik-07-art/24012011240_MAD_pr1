//  To Store & Display Values in Different Variables
fun main() {

    val age: Int = 21
    val cgpa: Double = 8.45
    val attendance: Float = 87.5f
    val enrollmentNo: Long = 24012011240L
    val semester: Short = 5
    val sectionNo: Byte = 2
    val grade: Char = 'A'
    val isPassed: Boolean = true
    val name: String = "Pratik"

    println("STUDENT PROFILE")
    println("Name: $name")
    println("Age: $age")
    println("CGPA: $cgpa")
    println("Attendance: $attendance%")
    println("Enrollment No: $enrollmentNo")
    println("Semester: $semester")
    println("Section: $sectionNo")
    println("Grade: $grade")
    println("Passed: $isPassed")
}